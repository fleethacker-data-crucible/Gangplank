// Generates web/icons.js from Lucide's SVG sources, so the UI ships only the icons it uses and
// never loads anything from a CDN (docs/UNIFIED-UI.md section 6).
//   npm pack lucide-static@1.54.0 && tar -xzf lucide-static-1.54.0.tgz
//   node tools/gen-icons.mjs package/icons
// The output is committed; re-run only when the icon list changes.
// The CSP allows no inline markup injection (app.js uses DOM APIs only), so the icons are emitted
// as element data and built with createElementNS: 16 px in controls, 20 px in navigation,
// 1.75 px stroke, currentColor.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const LUCIDE_VERSION = '1.54.0';
// Gangplank's icon name -> Lucide icon name.
const ICONS = {
  overview: 'layout-dashboard',
  changes: 'file-diff',
  branches: 'git-branch',
  compare: 'git-compare',
  history: 'history',
  reviews: 'git-pull-request',
  security: 'shield-check',
  settings: 'settings',
  help: 'circle-question-mark',
  power: 'power',
  themeSystem: 'sun-moon',
  themeLight: 'sun',
  themeDark: 'moon',
  collapse: 'panel-left-close',
  expand: 'panel-left-open',
  sparkles: 'sparkles',
  regenerate: 'rotate-ccw',
  next: 'arrow-right',
  external: 'external-link',
  refresh: 'refresh-cw',
  project: 'folder-git-2',
  warning: 'triangle-alert',
};

// Drop HTML comments until the text no longer contains <!--.
// One pass is not enough: <!<!--x-->--> becomes <!--> , which still starts a comment.
// A closer that never arrives drops the <!-- marker and keeps the tail.
export function stripHtmlComments(input) {
  let current = input;
  let previous;
  do {
    previous = current;
    const parts = [];
    let i = 0;
    while (i < current.length) {
      const start = current.indexOf('<!--', i);
      if (start < 0) { parts.push(current.slice(i)); break; }
      parts.push(current.slice(i, start));
      const end = current.indexOf('-->', start + 4);
      if (end < 0) { parts.push(current.slice(start + 4)); break; }
      i = end + 3;
    }
    current = parts.join('');
  } while (current !== previous);
  return current;
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
const dir = process.argv[2];
if (!dir) {
  console.error('usage: node tools/gen-icons.mjs <lucide-static>/icons');
  process.exit(1);
}
const data = {};
for (const [name, lucide] of Object.entries(ICONS)) {
  const svg = stripHtmlComments(readFileSync(path.join(dir, `${lucide}.svg`), 'utf8'));
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const nodes = [...inner.matchAll(/<([a-z]+)\s([^>]*?)\/?>/g)].map(([, tag, attrs]) => {
    const a = {};
    for (const [, k, v] of attrs.matchAll(/([a-z][a-z0-9-]*)="([^"]*)"/g)) a[k] = v;
    return [tag, a];
  });
  if (!nodes.length) throw new Error('No shapes in ' + lucide);
  data[name] = nodes;
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lines = Object.entries(data).map(([name, nodes]) => ` ${name}:${JSON.stringify(nodes)}, // ${ICONS[name]}`);
const out = `// GENERATED by tools/gen-icons.mjs from Lucide ${LUCIDE_VERSION} (ISC licence, https://lucide.dev). Do not edit.
'use strict';
(()=>{
const NS='http://www.w3.org/2000/svg';
const ICONS={
${lines.join('\n')}
};
// gangplankIcon('branches', 20) -> <svg> drawn in currentColor; 16 px in controls, 20 px in navigation.
function gangplankIcon(name,size){
 const svg=document.createElementNS(NS,'svg');const s=String(size||16);
 for(const [k,v] of Object.entries({class:'fl-icon',width:s,height:s,viewBox:'0 0 24 24',fill:'none',stroke:'currentColor','stroke-width':'1.75','stroke-linecap':'round','stroke-linejoin':'round','aria-hidden':'true',focusable:'false'}))svg.setAttribute(k,v);
 for(const [tag,attrs] of ICONS[name]||[]){const n=document.createElementNS(NS,tag);for(const [k,v] of Object.entries(attrs))n.setAttribute(k,v);svg.append(n)}
 return svg}
// Fill every <span data-icon="name" data-size="20"> already in the page.
function fill(scope){for(const x of (scope||document).querySelectorAll('[data-icon]'))x.replaceChildren(gangplankIcon(x.dataset.icon,Number(x.dataset.size)||16))}
window.gangplankIcon=gangplankIcon;window.gangplankFillIcons=fill;
fill();
})();
`;
writeFileSync(path.join(root, 'web', 'icons.js'), out);
console.log('wrote web/icons.js with ' + Object.keys(data).length + ' icons');
}
